"""Build web/engine.js: the openppc package and the sample files, as one script the page loads.

Run it after changing anything in openppc/ or examples/:

    python tools/build_web.py

tests/test_webapi.py fails when web/engine.js is out of date.
"""
import base64
import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "engine.js"
SAMPLES = ("search_terms_acme.csv", "keywords_acme.csv", "account_acme.json", "account_structure_acme.json",
           "ai_audit_sample.md")
# The modules the browser gets, by name: a new module ships only once it is listed here, so nothing that reaches the
# network can land in the app by accident. tests/test_fitness.py fails until every module is listed here or in
# NOT_BUNDLED.
BUNDLE = (
    "openppc/__init__.py", "openppc/checkfacts.py", "openppc/facts.py", "openppc/formats.py", "openppc/samples.py",
    "openppc/webapi.py",
    "openppc/engine/__init__.py", "openppc/engine/benchmarks.py", "openppc/engine/findings.py",
    "openppc/engine/trace.py", "openppc/engine/waste_model.py",
    "openppc/ingest/__init__.py", "openppc/ingest/account.py", "openppc/ingest/editor.py",
    "openppc/ingest/google_ads_csv.py",
    "openppc/templates/__init__.py", "openppc/templates/_common.py", "openppc/templates/account_read.py",
    "openppc/templates/account_structure.py", "openppc/templates/keyword_audit.py",
    "openppc/templates/search_term_waste.py",
)
# The command line and the MCP server: the app never runs them, and the MCP SDK is not in the browser.
NOT_BUNDLED = ("openppc/__main__.py", "openppc/cli.py", "openppc/mcp_server.py")


def templates():
    """The template list, so the Templates page shows it before the engine has loaded."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from openppc.templates import TEMPLATES
    return [{"name": t.NAME, "module": t.__name__.rsplit(".", 1)[1], "title": t.TITLE, "tier": t.TIER,
             "input": t.INPUT, "summary": t.SUMMARY} for t in TEMPLATES.values()]


SAMPLE_PATH = "/uploads/search_terms_acme.csv"  # where the app puts the sample export in the engine's files


def sample():
    """The sample's results, computed here by the same engine the browser runs, so "Try the sample" shows them at
    once while the engine downloads. The app uses them only for the untouched sample, never for your own files."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from openppc import webapi
    text = (ROOT / "examples" / "ai_audit_sample.md").read_text(encoding="utf-8")
    with tempfile.TemporaryDirectory() as folder:
        path = str(Path(folder) / "search_terms_acme.csv")
        shutil.copyfile(ROOT / "examples" / "search_terms_acme.csv", path)
        info = json.loads(webapi.inspect_file(path))
        paths = json.dumps([path])
        found = {"meta": json.loads(webapi.meta()), "info": info, "count": webapi.count_numbers(text, paths),
                 "check": json.loads(webapi.check(text, paths, "home-services")),
                 "audit": json.loads(webapi.audit("search-term-waste", path, "home-services", info["min_cost"], ""))}
    found["audit"]["token"] = None  # a token names an audit kept in the browser engine's memory: the app runs one there
    out = json.dumps(found, sort_keys=True)
    assert folder not in out, "a sample result names the build's folder"
    return found


def bundle():
    files = {name: (ROOT / name).read_text(encoding="utf-8") for name in BUNDLE}
    samples = {name: base64.b64encode((ROOT / "examples" / name).read_bytes()).decode("ascii")
               for name in SAMPLES}
    payload = json.dumps({"files": files, "samples": samples, "templates": templates(), "sample": sample(),
                          "sample_path": SAMPLE_PATH}, sort_keys=True, separators=(",", ":"))
    return ("// Generated by tools/build_web.py from openppc/ and examples/. Do not edit by hand.\n"
            f"globalThis.OPENPPC_BUNDLE = {payload};\n")


def main():
    OUT.write_text(bundle(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
